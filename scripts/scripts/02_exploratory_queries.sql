/* ---------- 1. Filtering & sorting ---------- */
-- Display the details where total expenses are greater than 40
SELECT * FROM Fact
WHERE [Total Expenses] > 40;

-- Display the date, product ID and sales where total expenses are between 100 and 200
SELECT [Date], Productid, Sales, [Total Expenses]
FROM Fact
WHERE [Total Expenses] BETWEEN 100 AND 200;

-- How many products are of regular type?
SELECT COUNT([Type]) AS Regular_Products
FROM PRODUCT
WHERE [Type] LIKE 'Reg%';

-- Display the details of the product where product type is coffee
SELECT * FROM PRODUCT
WHERE [Product Type] = 'Coffee';

-- Display state in a sequential order in the Location table
SELECT DISTINCT [State]
FROM [LOCATION]
ORDER BY [State];

-- Market details for area code 719
SELECT * FROM [LOCATION]
WHERE [Area Code] = 719;

/* ---------- 2. Aggregation & grouping ---------- */
-- Display total states
SELECT COUNT([State]) AS Total_States
FROM [LOCATION];

-- Distinct product types and their character length
SELECT DISTINCT [Type], LEN([Type]) AS Type_Length
FROM PRODUCT;

-- How much spending has been done on marketing of product ID 1?
SELECT Productid, SUM(Marketing) AS Marketing_Spending
FROM Fact
WHERE Productid = 1
GROUP BY Productid;

-- What is the minimum sales of a product?
SELECT MIN(Sales) AS Minimum_Sales FROM Fact;

-- Display the max Cost of Goods Sold (COGS)
SELECT MAX(COGS) AS Max_COGS FROM Fact;

-- What is the average sales in area code 719?
SELECT AVG(Sales) AS Avg_Sales
FROM Fact
WHERE [Area Code] = 719;

-- Display the average inventory for each product ID
SELECT Productid, AVG(Inventory) AS Avg_Inventory
FROM Fact
GROUP BY Productid;

-- Display the average budget of the product where the average budget margin > 100
SELECT Productid, AVG([Budget Sales]) AS Avg_Budget
FROM Fact
GROUP BY Productid
HAVING AVG([Budget Margin]) > 100;

-- What is the total sales done on date 2010-01-01?
SELECT SUM(Sales) AS Total_Sales
FROM Fact
WHERE [Date] = '2010-01-01';

-- Display the average total expense of each product ID on an individual date
SELECT [Date], Productid, AVG([Total Expenses]) AS Avg_Total_Expenses
FROM Fact
GROUP BY Productid, [Date];

/* ---------- 3. Joins ---------- */
-- Find out the total profit generated by Colorado state
SELECT SUM(f.Profit) AS Total_Profit
FROM Fact AS f
INNER JOIN [LOCATION] AS l ON f.[Area Code] = l.[Area Code]
WHERE l.[State] = 'Colorado';

-- Wide report: date, productID, product_type, product, sales, profit, state, area_code
SELECT f.[Date], p.Productid, p.[Product Type], p.PRODUCT,
       f.Sales, f.Profit, l.[State], l.[Area Code]
FROM Fact AS f
INNER JOIN PRODUCT  AS p ON f.Productid  = p.Productid
INNER JOIN [LOCATION] AS l ON f.[Area Code] = l.[Area Code];

-- 17. Find the state wise profit and sales
SELECT l.[State],
       SUM(f.Profit) AS Total_Profit,
       SUM(f.Sales)  AS Total_Sales
FROM Fact AS f
INNER JOIN [LOCATION] AS l ON f.[Area Code] = l.[Area Code]
GROUP BY l.[State]
ORDER BY l.[State] ASC;

-- Find the state wise profit and sales along with the product name
SELECT p.PRODUCT, l.[State],
       SUM(f.Profit) AS Total_Profit,
       SUM(f.Sales)  AS Total_Sales
FROM Fact AS f
INNER JOIN [LOCATION] AS l ON f.[Area Code] = l.[Area Code]
INNER JOIN PRODUCT  AS p ON f.Productid  = p.Productid
GROUP BY p.PRODUCT, l.[State];

-- Find the maximum profit along with the product ID and product type
SELECT f.Productid, p.[Product Type], MAX(f.Profit) AS Max_Profit
FROM Fact AS f
INNER JOIN PRODUCT AS p ON f.Productid = p.Productid
GROUP BY f.Productid, p.[Product Type];

/* ---------- 4. Calculated columns ---------- */
-- If there is an increase in sales of 5%, calculate the increased sales
SELECT DISTINCT Sales,
       ROUND(Sales * 0.05, 2) AS Increased_Amount,
       ROUND(Sales * 1.05, 2) AS Increased_Sales
FROM Fact
ORDER BY Sales;
